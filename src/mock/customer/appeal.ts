/** 本地占位图（SVG data URI），避免依赖外网图片 */
function placeholder(label: string, seed: number) {
  const bg = PALETTE[seed % PALETTE.length];
  const svg = `<svg xmlns="http://www.w3.org/2000/svg" width="400" height="300" viewBox="0 0 400 300"><rect width="400" height="300" fill="${bg}"/><text x="200" y="160" font-size="32" text-anchor="middle" fill="#fff" font-family="sans-serif">${label}</text></svg>`;
  return `data:image/svg+xml;charset=utf-8,${encodeURIComponent(svg)}`;
}

const images = (prefix: string, n: number, seed: number) =>
  Array.from({ length: n }, (_, i) => placeholder(`${prefix} ${i + 1}`, seed + i));

